#!/bin/bash

# Configuration
LINKEDIN_FILE="data/linkedin_clean_data.csv"
WUZZUF_FILE="data/wuzzuf_clean_data_v3.csv"

# Function to count jobs (lines - 1 header)
count_jobs() {
    if [ -f "$1" ]; then
        LINES=$(wc -l < "$1")
        if [ "$LINES" -gt 0 ]; then
            echo $(($LINES - 1))
        else
            echo 0
        fi
    else
        echo 0
    fi
}

# 1. Calculate Counts
LINKEDIN_COUNT=$(count_jobs "$LINKEDIN_FILE")
WUZZUF_COUNT=$(count_jobs "$WUZZUF_FILE")
TOTAL_COUNT=$(($LINKEDIN_COUNT + $WUZZUF_COUNT))

# Format with commas
F_LINKEDIN=$(printf "%'d" $LINKEDIN_COUNT)
F_WUZZUF=$(printf "%'d" $WUZZUF_COUNT)
F_TOTAL=$(printf "%'d" $TOTAL_COUNT)

echo "📊 Job Counts Check:"
echo "   🔵 LinkedIn: $F_LINKEDIN"
echo "   🟢 Wuzzuf:   $F_WUZZUF"
echo "   -------------------------"
echo "   📈 Total:    $F_TOTAL"

# 2. Update data/README.md (Live Dashboard)
DATA_README="data/README.md"
NOW=$(date "+%Y-%m-%d %H:%M:%S")

cat > "$DATA_README" <<EOF
# 📊 Data Statistics

> **Last Updated:** $NOW
> **Total Jobs:** $F_TOTAL

## 📁 File Breakdown

| Source | File Name | Job Count |
|--------|-----------|-----------|
| **LinkedIn** | [\`linkedin_clean_data.csv\`](linkedin_clean_data.csv) | **$F_LINKEDIN** |
| **Wuzzuf** | [\`wuzzuf_clean_data_v3.csv\`](wuzzuf_clean_data_v3.csv) | **$F_WUZZUF** |

## 📈 Summary
- **LinkedIn**: High-quality scraped data (Smart Scraper v3)
- **Wuzzuf**: Deduped and cleaned data
- **Total Coverage**: $F_TOTAL jobs across Egypt

---
*Auto-generated by update_data.sh*
EOF

echo "📄 Updated data/README.md"

# 3. Git Operations
echo "🚀 Staging changes..."
# Force add specific files to ensure they are tracked even if ignored
git add -f "$LINKEDIN_FILE" "$WUZZUF_FILE" "$DATA_README"
# Add any other new CSVs
git add data/*.csv 2>/dev/null

# Construct dynamic commit message
COMMIT_MSG="chore: update scraped data (Total: $F_TOTAL | LI: $F_LINKEDIN, WZ: $F_WUZZUF)"
echo "📝 Committing: $COMMIT_MSG"
git commit -m "$COMMIT_MSG"

echo "☁️ Pushing to GitHub..."
git push origin main

echo "✅ Done! All data updated successfully."
